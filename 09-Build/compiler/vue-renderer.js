function renderNode(n, depth) {
  const ind = '  '.repeat(depth);
  if (!n) return '';
  if (n.type === 'slot') return `${ind}{{ ${n.props?.propName || 'children'} }}`;
  if (n.type === 'text') return `${ind}${n.props?.value || ''}`;

  const tag = TAG_MAP[n.type] || 'div';
  const props = n.props || {};
  const parts = [];

  if (props.className) parts.push(`class="${props.className}"`);
  else if (props.class) parts.push(`class="${props.class}"`);
  if (props.role) parts.push(`role="${props.role}"`);
  if (props.conditional === 'v-if') parts.push('v-if="open"');
  if (n.type === 'closeButton') parts.push('@click="$emit(\'close\')"');

  const children = (n.children || []).map(c => renderNode(c, depth + 1)).filter(Boolean);
  const childrenStr = children.length ? '\n' + children.join('\n') + '\n' + ind : '';
  const blockTags = ['div', 'span', 'p', 'section', 'header', 'footer', 'main', 'nav', 'form', 'ul', 'ol', 'li', 'table', 'label', 'select', 'textarea', 'a', 'button', 'svg', 'h2'];

  let el;
  if (blockTags.includes(tag) || children.length) {
    el = `<${tag}${parts.length ? ' ' + parts.join(' ') : ''}>${childrenStr}</${tag}>`;
  } else {
    el = `<${tag}${parts.length ? ' ' + parts.join(' ') : ''} />`;
  }
  return `${ind}${el}`;
}

